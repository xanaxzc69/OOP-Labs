namespace ClinicApp.Interfaces;

// Задача 1. Контракт «це можна оплатити».
// Інтерфейс не містить реалізації — лише перелік того, що зобов'язаний
// уміти клас, який його підписує. Підписати контракт може будь-який клас,
// не лише Appointment.
public interface IPayable
{
    // Сума до сплати
    decimal Amount { get; }

    // Чи вже оплачено
    bool IsPaid { get; }

    // Позначити оплаченим. Повертає false, якщо оплата неможлива
    bool MarkPaid();
}
