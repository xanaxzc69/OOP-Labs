namespace ClinicApp.Interfaces;

// Задача 4 (Lab09). Контракт «у мене є ідентифікатор».
//
// Навіщо він потрібен: узагальнений клас за замовчуванням нічого не знає про
// свій параметр типу T. Для Repository<T> цього замало — щоб шукати й видаляти
// елементи за номером, репозиторій має бути впевнений, що в кожного T є Id.
// Саме цю гарантію й дає обмеження where T : IIdentifiable: компілятор
// пропустить у репозиторій лише ті типи, які підписали цей контракт.
//
// Лише get: ідентифікатор призначається один раз у конструкторі
// і ззовні не змінюється.
public interface IIdentifiable
{
    int Id { get; }
}
